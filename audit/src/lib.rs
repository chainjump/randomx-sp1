/// Returns the canonical RandomX commitment `Blake2b-256(input || hash)`.
pub fn calculate_commitment(input: &[u8], hash: &[u8; 32]) -> [u8; 32] {
    let mut state = blake2b_simd::Params::new().hash_length(32).to_state();
    state.update(input);
    state.update(hash);
    state
        .finalize()
        .as_bytes()
        .try_into()
        .expect("Blake2b-256 always returns 32 bytes")
}

