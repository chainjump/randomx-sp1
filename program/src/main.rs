#![no_main]

use std::sync::Arc;

use rustdom_x::{new_vm, VmMemory};
use rustdom_x_compact_vm::calculate_hash;

sp1_zkvm::entrypoint!(main);

// Exact fixed statement used by the accepted full-claim guest.
const RANDOMX_SEED: [u8; 32] = [
    0x11, 0xc7, 0x98, 0xe5, 0xac, 0x65, 0x15, 0x21, 0x8b, 0xc3, 0xef, 0xcb, 0x54, 0x16, 0xe5, 0xb6,
    0x8c, 0x59, 0x9e, 0x42, 0xa6, 0x1b, 0x86, 0xef, 0xe5, 0x74, 0x6b, 0xb7, 0x8e, 0xb4, 0xbe, 0x8e,
];

const HASHING_BLOB: [u8; 76] = [
    0x10, 0x10, 0xc5, 0xa2, 0x99, 0xd3, 0x06, 0x5e, 0xd0, 0x66, 0x57, 0x3b, 0x62, 0xcd, 0xcc, 0x0d,
    0x24, 0x3d, 0x8b, 0x71, 0x30, 0xcf, 0x8b, 0xe8, 0x7f, 0xf7, 0x1e, 0xc3, 0x02, 0xce, 0xdd, 0x31,
    0xdb, 0x9f, 0x6f, 0x4f, 0x6e, 0x10, 0xe8, 0x5d, 0x5a, 0x4c, 0x10, 0x76, 0xf9, 0xef, 0x57, 0xaa,
    0xbb, 0x92, 0x00, 0x4f, 0xaf, 0xeb, 0xc6, 0x8b, 0x9a, 0x54, 0xbc, 0x9d, 0x35, 0x84, 0xec, 0x8f,
    0x94, 0x3e, 0x94, 0x9b, 0xc4, 0xc3, 0x72, 0xa5, 0xf3, 0xb4, 0xe6, 0x1d,
];

const EXPECTED_POW_HASH: [u8; 32] = [
    0x04, 0x3f, 0x95, 0xd6, 0xe6, 0x12, 0xd7, 0xc9, 0x68, 0x79, 0xdd, 0x25, 0xab, 0x78, 0x45, 0x64,
    0x81, 0xcf, 0xbb, 0x63, 0x01, 0x43, 0xa5, 0x20, 0x1c, 0x38, 0x92, 0x00, 0x00, 0x00, 0x00, 0x00,
];

pub fn main() {
    let memory = Arc::new(VmMemory::light(&RANDOMX_SEED));
    let mut vm = new_vm(memory);
    let hash = calculate_hash(&mut vm, &HASHING_BLOB);

    assert_eq!(hash.as_bytes(), EXPECTED_POW_HASH);
    sp1_zkvm::io::commit_slice(hash.as_bytes());
}
