#[cfg(all(feature = "cache-only", feature = "no-memory-hash"))]
compile_error!("select exactly one profiling probe");

#[cfg(feature = "cache-only")]
pub fn main() {
    let memory = VmMemory::light(&RANDOMX_SEED);
    let blocks = memory.seed_memory.blocks();
    let words = [
        blocks[0][0],
        blocks[blocks.len() / 2][64],
        blocks[blocks.len() - 1][127],
        memory.seed_memory.program_count() as u64,
    ];
    let mut output = [0u8; 32];
    for (chunk, word) in output.chunks_exact_mut(8).zip(words) {
        chunk.copy_from_slice(&word.to_le_bytes());
    }
    sp1_zkvm::io::commit_slice(&output);
}

#[cfg(feature = "no-memory-hash")]
pub fn main() {
    let memory = Arc::new(VmMemory::no_memory());
    let mut vm = new_vm(memory);
    let hash = calculate_hash(&mut vm, &HASHING_BLOB);
    sp1_zkvm::io::commit_slice(hash.as_bytes());
}
